#!/usr/bin/env python3
"""Turns the word "OpenTrust" into vector outlines (scripts/wordmark_path.py) in Nunito Sans Black, narrowed to match the logo's
lettering. A background-image SVG can't load web fonts, so the scene draws the text as a path instead.
Needs fonttools + uharfbuzz and the Nunito Sans variable font (SIL Open Font License, github.com/google/fonts/tree/main/ofl/nunitosans):
  python3 scripts/outline_wordmark.py /path/to/NunitoSans[YTLC,opsz,wdth,wght].ttf"""
import sys, tempfile, os
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
import uharfbuzz as hb

TEXT, AXES = "OpenTrust", {"wght": 900, "wdth": 82, "opsz": 12, "YTLC": 500}

src = TTFont(sys.argv[1])
static = instancer.instantiateVariableFont(src, AXES)           # a fixed-weight copy (keeps kerning)
tmp = os.path.join(tempfile.mkdtemp(), "static.ttf"); static.save(tmp)
upem = static["head"].unitsPerEm; glyphs = static.getGlyphSet(); order = static.getGlyphOrder()

blob = hb.Blob.from_file_path(tmp); face = hb.Face(blob); font = hb.Font(face)
buf = hb.Buffer(); buf.add_str(TEXT); buf.guess_segment_properties(); hb.shape(font, buf, {"kern": True, "liga": False})

pen = SVGPathPen(glyphs); x = 0
for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
    name = order[info.codepoint]
    glyphs[name].draw(TransformPen(pen, (1, 0, 0, 1, x + pos.x_offset, pos.y_offset)))
    x += pos.x_advance
cap = static["OS/2"].sCapHeight
open("scripts/wordmark_path.py", "w").write(
    "# Generated by scripts/outline_wordmark.py. Font units, y-up; baseline at y=0.\n"
    f"UPEM = {upem}\nWIDTH = {x}\nCAP_HEIGHT = {cap}\nD = {pen.getCommands()!r}\n")
print(f"wrote scripts/wordmark_path.py: width {x} units = {x/upem:.3f} em, cap height {cap/upem:.3f} em, path {len(pen.getCommands())} chars")
